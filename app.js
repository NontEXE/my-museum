function navigateToArtwork(slug) {
  if (window.location.hash.slice(1) === slug) {
    openDetail(slug);
    return;
  }
  window.location.hash = slug;
}

function renderBookmarkState(artwork) {
  const saved = isBookmarked(artwork.slug);
  refs.bookmarkButton.setAttribute("aria-pressed", String(saved));
  refs.bookmarkButton.textContent = saved ? "เก็บไว้แล้ว" : "เก็บไว้ใกล้ใจ";
  refs.bookmarkButton.setAttribute("aria-label", saved ? "นำภาพนี้ออกจากรายการเก็บไว้ใกล้ใจ" : "เก็บภาพนี้ไว้ใกล้ใจ");
}

function applyZoomSize() {
  if (!activeArtwork) return;
  const stage = refs.zoomStage;
  const image = refs.detailImage;
  const naturalWidth = image.naturalWidth || activeArtwork.image.detail.width;
  const naturalHeight = image.naturalHeight || activeArtwork.image.detail.height;
  const stageWidth = Math.max(stage.clientWidth, 1);
  const stageHeight = Math.max(stage.clientHeight, 1);
  const fitScale = Math.min(stageWidth / naturalWidth, stageHeight / naturalHeight, 1);
  const displayWidth = Math.round(naturalWidth * fitScale * imageZoom);
  const displayHeight = Math.round(naturalHeight * fitScale * imageZoom);

  image.style.width = `${displayWidth}px`;
  image.style.height = `${displayHeight}px`;
  refs.zoomValue.textContent = `${Math.round(imageZoom * 100)}%`;
  refs.zoomSlider.value = imageZoom;
  refs.zoomStage.classList.toggle("is-zoomed", imageZoom > 1);
  refs.zoomOutButton.disabled = imageZoom <= 1;
  refs.zoomResetButton.disabled = imageZoom <= 1;
  refs.zoomInButton.disabled = imageZoom >= 6;
}

function setImageZoom(nextZoom, origin = null) {
  if (!activeArtwork) return;
  const stage = refs.zoomStage;
  const rect = typeof stage.getBoundingClientRect === "function" ? stage.getBoundingClientRect() : { left: 0, top: 0 };
  const previousWidth = Math.max(stage.scrollWidth, stage.clientWidth, 1);
  const previousHeight = Math.max(stage.scrollHeight, stage.clientHeight, 1);
  const anchorX = origin ? origin.clientX - rect.left : stage.clientWidth / 2;
  const anchorY = origin ? origin.clientY - rect.top : stage.clientHeight / 2;
  const ratioX = (stage.scrollLeft + anchorX) / previousWidth;
  const ratioY = (stage.scrollTop + anchorY) / previousHeight;

  imageZoom = Math.min(6, Math.max(1, Math.round(nextZoom * 100) / 100));
  applyZoomSize();

  if (imageZoom === 1) {
    stage.scrollTo({ left: 0, top: 0 });
    return;
  }

  requestAnimationFrame(() => {
    stage.scrollLeft = Math.max(0, ratioX * stage.scrollWidth - anchorX);
    stage.scrollTop = Math.max(0, ratioY * stage.scrollHeight - anchorY);
  });
}

function resetImageZoom() {
  imageZoom = 1;
  applyZoomSize();
  refs.zoomStage.scrollTo({ left: 0, top: 0 });
}

function startImageDrag(event) {
  if (imageZoom <= 1 || event.button !== 0) return;
  dragState = {
    pointerId: event.pointerId,
    x: event.clientX,
    y: event.clientY,
    scrollLeft: refs.zoomStage.scrollLeft,
    scrollTop: refs.zoomStage.scrollTop
  };
  refs.zoomStage.classList.add("is-dragging");
  refs.zoomStage.setPointerCapture(event.pointerId);
}

function moveImageDrag(event) {
  if (!dragState || dragState.pointerId !== event.pointerId) return;
  refs.zoomStage.scrollLeft = dragState.scrollLeft - (event.clientX - dragState.x);
  refs.zoomStage.scrollTop = dragState.scrollTop - (event.clientY - dragState.y);
}

function endImageDrag(event) {
  if (!dragState || dragState.pointerId !== event.pointerId) return;
  refs.zoomStage.classList.remove("is-dragging");
  dragState = null;
}

function handleZoomWheel(event) {
  if (!activeArtwork) return;
  event.preventDefault();
  const factor = event.deltaY < 0 ? 1.08 : 0.92;
  setImageZoom(imageZoom * factor, event);
}

function setImageExpanded(expanded) {
  imageExpanded = expanded;
  refs.detailPanel.classList.toggle("is-image-expanded", imageExpanded);
  refs.zoomExpandButton.setAttribute("aria-pressed", String(imageExpanded));
  refs.zoomExpandButton.textContent = imageExpanded ? "ออก" : "เต็มภาพ";
  refs.zoomExpandButton.setAttribute("aria-label", imageExpanded ? "ออกจากโหมดดูภาพเต็มพื้นที่" : "ดูภาพเต็มพื้นที่");
  window.setTimeout(applyZoomSize, 0);
  refs.zoomStage.focus({ preventScroll: true });
}

function toggleImageExpanded() {
  setImageExpanded(!imageExpanded);
}

function openDetail(slug) {
  const artwork = bySlug.get(slug);
  if (!artwork) return;

  if (!activeArtwork) {
    scrollBeforeDetail = window.scrollY;
    previousFocus = document.activeElement;
  }

  activeArtwork = artwork;
  setImageExpanded(false);
  resetImageZoom();
  refs.detailImage.src = artwork.image.detail.src;
  refs.detailImage.width = artwork.image.detail.width;
  refs.detailImage.height = artwork.image.detail.height;
  refs.detailImage.alt = artwork.alt;
  refs.detailCounter.textContent = `${String(artwork.index).padStart(2, "0")} / ${artworks.length}`;
  refs.detailThemes.textContent = formatThemes(artwork.themes);
  refs.detailTitle.textContent = artwork.originalTitle ? `${artwork.title} · ${artwork.originalTitle}` : artwork.title;
  refs.detailMeta.textContent = `${artwork.artist} · ${artwork.year}`;
  refs.detailOpening.textContent = artwork.opening;
  refs.detailMeaning.innerHTML = paragraphs(artwork.personalMeaning);
  refs.detailOrigin.innerHTML = paragraphs(artwork.origin);
  refs.detailQuote.textContent = artwork.dailyQuote;
  refs.creditArtwork.textContent = artwork.title;
  refs.creditArtist.textContent = artwork.artist;
  refs.creditYear.textContent = artwork.year;
  renderBookmarkState(artwork);

  refs.detailLayer.hidden = false;
  refs.detailLayer.setAttribute("aria-hidden", "false");
  document.body.classList.add("detail-open");
  window.setTimeout(applyZoomSize, 0);
  window.setTimeout(() => refs.bookmarkButton.focus({ preventScroll: true }), 0);
}

function closeDetail(options = {}) {
  if (!activeArtwork) return;
  activeArtwork = null;
  refs.detailLayer.hidden = true;
  refs.detailLayer.setAttribute("aria-hidden", "true");
  refs.detailImage.removeAttribute("src");
  refs.detailImage.removeAttribute("style");
  refs.zoomStage.classList.remove("is-zoomed", "is-dragging");
  refs.detailPanel.classList.remove("is-image-expanded");
  refs.zoomExpandButton.setAttribute("aria-pressed", "false");
  refs.zoomExpandButton.textContent = "เต็มภาพ";
  imageExpanded = false;
  dragState = null;
  document.body.classList.remove("detail-open");

  if (!options.fromHash && window.location.hash) {
    history.pushState("", document.title, window.location.pathname + window.location.search);
  }
  window.scrollTo({ top: scrollBeforeDetail, behavior: "auto" });
  if (previousFocus && typeof previousFocus.focus === "function") {
    previousFocus.focus({ preventScroll: true });
  }
}

function adjacentArtwork(direction) {
  if (!activeArtwork) return null;
  const currentIndex = artworks.findIndex((artwork) => artwork.slug === activeArtwork.slug);
  return artworks[(currentIndex + direction + artworks.length) % artworks.length];
}

function handleHash() {
  const slug = decodeURIComponent(window.location.hash.replace(/^#/, ""));
  if (!slug) {
    closeDetail({ fromHash: true });
    return;
  }
  if (bySlug.has(slug)) {
    openDetail(slug);
  }
}

function toggleBookmark() {
  if (!activeArtwork) return;
  const bookmarks = getBookmarks();
  if (bookmarks.has(activeArtwork.slug)) bookmarks.delete(activeArtwork.slug);
  else bookmarks.add(activeArtwork.slug);
  setBookmarks(bookmarks);
  renderBookmarkState(activeArtwork);
  updateBookmarkCount();
  if (activeFilter === "saved") renderGallery();
}

function handleKeyboard(event) {
  if (!activeArtwork) return;
  if (event.key === "Escape") {
    event.preventDefault();
    if (imageExpanded) {
      setImageExpanded(false);
      return;
    }
    closeDetail();
  }
  if (event.key === "ArrowLeft") {
    event.preventDefault();
    navigateToArtwork(adjacentArtwork(-1).slug);
  }
  if (event.key === "ArrowRight") {
    event.preventDefault();
    navigateToArtwork(adjacentArtwork(1).slug);
  }
  if (event.key === "+" || event.key === "=") {
    event.preventDefault();
    setImageZoom(imageZoom + 0.25);
  }
  if (event.key === "-") {
    event.preventDefault();
    setImageZoom(imageZoom - 0.25);
  }
  if (event.key === "0") {
    event.preventDefault();
    resetImageZoom();
  }
}

let revealObserver = null;
function observeReveals(nodes) {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    nodes.forEach((node) => node.classList.add("is-visible"));
    return;
  }
  if (!revealObserver) {
    revealObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12 });
  }
  nodes.forEach((node) => revealObserver.observe(node));
}

function bindNavigationFilters() {
  const filterLinks = new Map([
    ["#self", "self"],
    ["#tyler", "tyler"],
    ["#journey", "journey"]
  ]);

  $$(".site-nav a").forEach((link) => {
    link.addEventListener("click", (event) => {
      const filter = link.dataset.filterLink || filterLinks.get(link.getAttribute("href"));
      if (filter) {
        event.preventDefault();
        setFilter(filter);
        document.getElementById("gallery").scrollIntoView({ block: "start" });
      }
      closeMenu();
    });
  });
}

function closeMenu() {
  refs.nav.classList.remove("is-open");
  refs.menuToggle.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}

